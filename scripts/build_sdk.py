#!/usr/bin/env python3
"""Generate one-file browser/CommonJS SDK from one authoritative lifecycle source.
No runtime script injection, import, fetch, or sibling-file require is needed.
"""
import pathlib
import sys
ROOT = pathlib.Path(__file__).resolve().parents[1]


def bundle():
    engine = (ROOT / "assets/availability.js").read_text()
    core = (ROOT / "src/client-core.js").read_text().strip()
    return """/* GENERATED by scripts/build_sdk.py. Edit src/client-core.js or assets/availability.js. */
(function (root, factory) {
  // Evaluate the single maintained lifecycle implementation inside a private CommonJS capsule.
  var engine = { exports: {} };
  (function (module) {
""" + engine + """
  })(engine);
  var api = factory(engine.exports);
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.LLMPrice = api;
})(typeof globalThis !== "undefined" ? globalThis : this,
""" + core + ");\n"


def check():
    return (ROOT / "assets/client.js").read_text() == bundle()


if __name__ == "__main__":
    if "--check" in sys.argv:
        raise SystemExit(0 if check() else "SDK bundle stale; run python3 scripts/build_sdk.py")
    (ROOT / "assets/client.js").write_text(bundle())
    print("generated standalone assets/client.js (no runtime dependency loading)")
